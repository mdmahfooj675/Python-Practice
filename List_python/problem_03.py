# Print the sum, maximum and minimum of a list using built-in functions

print("question -> Print the sum, maximum and minimum of a list using built-in functions")

number = [45 , 67 ,87, 89, 98 , 90 ,56]

# to print the maximum using max function
print("maximum element of the given list : " , max(number))

# to print the minimum using max function
print("minimum element of the given list : " , min(number))

# to print the sum of the element using sum function
print("sum os the all element present in the list : " , sum(number))

